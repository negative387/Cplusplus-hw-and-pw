#include <iostream>
#include "StringArray.h"

/*
Завдання 1 питання:

1. Чому конструктор StringArray(int arrayLength) позначено як explicit? Що трапиться без цього ключового слова?
2. Чому виділення пам'яті для std::string (new std::string[n]) викликає конструктори рядків за замовчуванням для кожного елемента?
3. Чому в деструкторі викликається саме delete[] data, а не просто delete data?

1 - Тому що explicit забороняє компилятору зробити неявне перетворення типів. Може бути не передбачувані помилки.
2 - Тому що це безпечно, бо без конструктора у масиві буде сміття і тоді програмі капут.
3 - Бо це масив, а не просто поінтер. Без [] він видалить тільки перший елемент.


Завдання 2 питання:

1. Чому необхідно створювати дві версії operator[] — звичайну та константну?
2. Що відбудеться, якщо прибрати const з поверненого типу const std::string& operator[](int) const?
3. Чому після delete[] data обов'язково встановлювати data = nullptr?

1 - Бо масиви можуть бути констатними
2 - Помилка компіляції, бо якщо вона приймає констатний масив, то і потрібна повертати також константу.
3 - Щоб після видалення даних у масиву, поінтер на неї не вказувала на ту ж пам'ять.


Завдання 3 питання:

1. Чому для класів, що володіють динамічними ресурсами, стандартний конструктор копіювання призводить до збою програми (crash)?
2. Що станеться в операторі operator=, якщо не зробити перевірку if (this == &other) і виконати delete[] data?
3. Що таке «глибоке копіювання» (deep copy) на відміну від «поверхневого» (shallow copy)?

1 - Бо вони копіюють одну саме місце у пам'яті. Через це деструктор пробує видалити одну і теж пам'ять 2 рази.
2 - Він може видалити дані самого себе (array = array).
3 - «глибоке копіювання» виділяє нову пам'ять для копії.


Завдання 4 питання:

1. Чому при кожній вставці чи видаленні поточна реалізація вимагає повного перекопіювання масиву? Яка часова складність (O)?
2. Чому для insertBefore коректним є індекс length, а для remove — ні?

1 - Бо нам потрібний новий розмір пам'яті, а у старого масива фіксований розмір. Цього я не знав, але загугливши, начебто O(N).
2 - Для insertBefore коректний бо там потрібно знайти де додати рядок, а у remove потрібно видалити вже існуючий рядок (length - 1).
*/

int main() {

    std::cout << "=== Тест 1: Конструктори та розмір ===\n";

    // Порожній масив:
    StringArray array1;
    std::cout << "Порожній масив: довжина = " << array1.getLength()
              << ", isEmpty = " << std::boolalpha << array1.isEmpty() << "\n";

    // Фіксований масив:
    StringArray array2(3);
    std::cout << "Фіксований масив на 3 рядки: довжина = " << array2.getLength()
              << ", isEmpty = " << std::boolalpha << array2.isEmpty() << "\n";

    // Масив зі списку ініціалізації:
    StringArray array3 = {"C++", "OOP", "String", "Array"};
    std::cout << "Масив зі списку ініціалізації: довжина = " << array3.getLength()
              << ", isEmpty = " << std::boolalpha << array3.isEmpty() << "\n";

    // Перевірка винятку (з цим допоміг ЩІ бо ми цього не проходили окрім пайтон):
    try {
        StringArray arrayWrong(-5);
    } catch (const std::invalid_argument& error) {
        std::cout << "Спроба створити масив з розміром -5: Очікуваний виняток: " << error.what() << "\n";
    }


    std::cout << "\n\n=== Тест 2: Індексація та очищення ===\n";

    StringArray array4 = {"C++", "Python", "Rust"};
    std::cout << "Початковий масив: " << array4 << "\n";
    std::cout << "Елемент [1]: " << array4[1] << "\n";

    // Модифікація значення за індексом:
    array4[1] = "Go";
    std::cout << "Після заміни [1] на \"Go\": " << array4 << "\n";

    // Читання з константного посилання:
    std::cout << "Тест константного доступу: ";
    printConstElement(array4, 2);
    std::cout << "\n";

    // Перехоплення винятку std::out_of_range:
    try {
        std::cout << "Спроба доступу до індексу 10: ";
        std::cout << array4[10] << "\n"; // Генерує виняток
    } catch (const std::out_of_range& e) {
        std::cout << "Перехоплено std::out_of_range: " << e.what() << "\n";
    }

    // Очищення через erase():
    array4.erase();
    std::cout << "Після erase(): довжина = " << array4.getLength()
              << ", isEmpty = " << ( array4.isEmpty() ? "true" : "false" ) << "\n";


    std::cout << "\n\n=== Тест 3: Глибоке копіювання ===\n";

    StringArray original = {"Alpha", "Bravo", "Charlie"};
    std::cout << "Оригінал: " << original << "\n";

    // Створення копії:
    std::cout << "Створено копію copyArray\n";
    StringArray copyArray = original;

    // Модифікація копії та перевірка незалежності оригінала:
    copyArray[0] = "ZULU";
    std::cout << "Змінено copyArray[0] на \"ZULU\"\n";
    std::cout << "Копія: " << copyArray << "\n";
    std::cout << "Оригінал: " << original << " -> Не змінився! (Глибоке копіювання працює)\n";

    // Тест на самоприсвоювання (a = a):
    original = original;
    std::cout << "Тест самоприсвоювання (array = array) пройшов успішно.\n";

    // Ланцюгове присвоювання (a = b = c):
    StringArray a, b;
    a = b = original; // Присвоюємо значення оригінала спочатку в b, а потім в a
    std::cout << "Ланцюгове присвоювання:\n";
    std::cout << "Масив a: " << a << "\n";
    std::cout << "Масив b: " << b << "\n";


    std::cout << "\n\n=== Тест 4: Зміна розміру, вставка та видалення ===\n";

    StringArray array = {"HTML", "CSS"};
    std::cout << "Початковий: " << array << "\n";

    // Додавання на початок
    array.insertAtBeginning("HTTP");
    std::cout << "insertAtBeginning(\"HTTP\"): " << array << "\n";

    // Додавання в кінець
    array.insertAtEnd("JS");
    std::cout << "insertAtEnd(\"JS\"):         " << array << "\n";

    // Вставка в середину перед індексом 2
    array.insertBefore("SQL", 2);
    std::cout << "insertBefore(\"SQL\", 2):    " << array << "\n";

    // Видалення елемента HTML (він зараз під індексом 1)
    array.remove(1);
    std::cout << "remove(1) (видаляємо HTML): " << array << "\n";

    // Зменшення розміру (обрізання до двух елементів)
    array.resize(2);
    std::cout << "resize(2) (обрізаємо):     " << array << "\n";

    // Збільшення розміру (до 4-х елементів, нові заповнюються порожніми рядками)
    array.resize(4);
    std::cout << "resize(4) (розширюємо):    " << array << "\n";

    return 0;
}